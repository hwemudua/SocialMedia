import pandas as pd, matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
a=pd.read_csv('/mnt/user-data/uploads/850675c9-va_price_income.csv').rename(columns={'ratio':'r_all'})
o=pd.read_csv('/mnt/user-data/uploads/7adf7297-va_owner_price_income.csv')
d=o.merge(a[['NAME','r_all']],on='NAME')
med_o=d.ratio.median()
pick=['Rappahannock County','Arlington County','Falls Church city','Alexandria city','Charlottesville city','Fairfax County','Loudoun County','Richmond city','Harrisonburg city','Virginia Beach city','Roanoke city','Lee County','Martinsville city']
s=d[d.NAME.str.replace(', Virginia','').isin(pick)].copy()
s['short']=s.NAME.str.replace(', Virginia','').str.replace(' County','').str.replace(' city',' (city)')
s=s.sort_values('ratio').reset_index(drop=True)
INK,MUTE,GRID,ACC,GRAY='#1f2937','#6b7280','#e5e7eb','#1d4ed8','#9ca3af'
fig,ax=plt.subplots(figsize=(12,6.75),dpi=150)
for i,r in s.iterrows():
    ax.plot([r.ratio,r.r_all],[i,i],color=GRAY,lw=2,zorder=2,solid_capstyle='round')
    ax.scatter(r.r_all,i,s=70,facecolor='white',edgecolor=GRAY,linewidth=2,zorder=3)
    ax.scatter(r.ratio,i,s=80,color=ACC,edgecolor='white',linewidth=1.2,zorder=4)
    ax.text(r.ratio-0.12,i,f'{r.ratio:.1f}x',ha='right',va='center',fontsize=10.5,color=ACC,fontweight='bold')
    ax.text(r.r_all+0.12,i,f'{r.r_all:.1f}x',ha='left',va='center',fontsize=10.5,color=MUTE)
ax.axvline(med_o,color=INK,lw=1,ls=(0,(4,3)),zorder=1)
ax.text(med_o+0.05,len(s)-0.35,f'Median locality (owners): {med_o:.1f}x',fontsize=10.5,color=INK,fontweight='bold',va='bottom')
ax.set_yticks(range(len(s))); ax.set_yticklabels(s.short,fontsize=11.5,color=INK)
ax.set_xlim(0.9,7.2); ax.set_ylim(-0.7,len(s)+0.2)
ax.set_xticks([2,3,4,5,6,7]); ax.set_xticklabels([f'{v}x' for v in [2,3,4,5,6,7]],color=MUTE,fontsize=11)
ax.grid(axis='x',color=GRID,lw=0.8,zorder=0)
for sp in ax.spines.values(): sp.set_visible(False)
ax.tick_params(length=0)
# legend (direct, top-right)
ax.scatter(5.55,2.0,s=80,color=ACC,edgecolor='white',linewidth=1.2); ax.text(5.72,2.0,'Homeowner households only',va='center',fontsize=11,color=INK)
ax.scatter(5.55,1.1,s=70,facecolor='white',edgecolor=GRAY,linewidth=2); ax.text(5.72,1.1,'All households (incl. renters)',va='center',fontsize=11,color=INK)
fig.text(0.04,0.94,'Count only homeowners, and Virginia\'s home-price gap shrinks',fontsize=18,fontweight='bold',color=INK)
fig.text(0.04,0.895,'Median home value ÷ median household income, selected localities. Charlottesville falls from 2nd to 10th of 133.',fontsize=12,color=MUTE)
fig.text(0.04,0.03,'Source: Census ACS 2019–2023 5-yr (B25077, B25119, B19013). Ratio of medians; small localities carry margins of error of ~10–15% on income.   @thedocshango.bsky.social',fontsize=8.5,color=MUTE)
fig.subplots_adjust(left=0.17,right=0.97,top=0.85,bottom=0.1)
fig.savefig('out/va_owner_price_to_income.png',facecolor='white')
